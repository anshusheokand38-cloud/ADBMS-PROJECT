DECLARE
    CURSOR STUDENT_CURSOR IS
        SELECT ROLL_NO, NAME, MARKS
        FROM CAMPUS_STUDENT
        ORDER BY ROLL_NO;

    V_ROLL_NO CAMPUS_STUDENT.ROLL_NO%TYPE;
    V_NAME CAMPUS_STUDENT.NAME%TYPE;
    V_MARKS CAMPUS_STUDENT.MARKS%TYPE;

BEGIN
    OPEN STUDENT_CURSOR;

    LOOP
        FETCH STUDENT_CURSOR
        INTO V_ROLL_NO, V_NAME, V_MARKS;

        EXIT WHEN STUDENT_CURSOR%NOTFOUND;

        DBMS_OUTPUT.PUT_LINE(
            'Roll No: ' || V_ROLL_NO ||
            ', Name: ' || V_NAME ||
            ', Marks: ' || V_MARKS
        );
    END LOOP;

    CLOSE STUDENT_CURSOR;

EXCEPTION
    WHEN OTHERS THEN
        IF STUDENT_CURSOR%ISOPEN THEN
            CLOSE STUDENT_CURSOR;
        END IF;

        DBMS_OUTPUT.PUT_LINE('Error: ' || SQLERRM);
END;

